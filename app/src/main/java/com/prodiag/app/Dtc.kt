/** شرح فارسی کد؛ اگر در جدول نبود، دسته‌ی کلی کد را از ساختار آن نشان می‌دهد. */
fun describeDtc(code: String): String {
    PERSIAN_DTC[code]?.let { return it }
    val sys = when (code.firstOrNull()) {
        'P' -> "موتور/گیربکس"
        'B' -> "بدنه"
        'C' -> "شاسی"
        'U' -> "شبکه ارتباطی"
        else -> "نامشخص"
    }
    val generic = code.getOrNull(1) == '0' || code.getOrNull(1) == '2'
    val area = if (code.firstOrNull() == 'P') when (code.getOrNull(2)) {
        '0', '1' -> "اندازه‌گیری هوا و سوخت"
        '2' -> "مدار انژکتور / پمپ سوخت"
        '3' -> "سیستم جرقه یا احتراق ناقص"
        '4' -> "کنترل آلایندگی"
        '5' -> "کنترل سرعت و دور آرام"
        '6' -> "کامپیوتر (ECU) و مدارهای خروجی"
        '7', '8', '9' -> "گیربکس"
        else -> ""
    } else ""
    return "بخش $sys" + (if (area.isNotEmpty()) " - $area" else "") +
        (if (generic) " (کد استاندارد)" else " (کد مخصوص سازنده)") +
        " - شرح دقیق در جدول نیست؛ شماره‌ی کد را در مستندات همان خودرو بررسی کنید"
}

fun decodeDtc(b1: Int, b2: Int): String =
    fmt("%c%d%X%02X", "PCBU"[b1 shr 6], (b1 shr 4) and 3, b1 and 0xF, b2)

/**
 * پاسخ خام حالت‌های 03 / 07 / 0A را به لیست کد تبدیل می‌کند.
 * resp = "43" یا "47" یا "4A"؛ can=true یعنی بایت تعداد خطا بعد از آن وجود دارد.
 */
fun parseDtcs(resp: String, can: Boolean, respId: String = "43"): List<String> {
    val prefixed = Regex("^([0-9]):(.*)$")
    val records = mutableListOf<StringBuilder>()
    for (raw in resp.lines()) {
        val l = raw.replace(" ", "").uppercase()
        if (l.isEmpty() || !l.all { it in "0123456789ABCDEF:" }) continue
        val m = prefixed.find(l)
        if (m != null) {
            if (m.groupValues[1] == "0") records += StringBuilder(m.groupValues[2])
            else records.lastOrNull()?.append(m.groupValues[2])
        } else if (l.startsWith(respId)) {
            records += StringBuilder(l)
        }
    }
    val out = linkedSetOf<String>()
    for (rec in records) {
        var s = rec.toString()
        if (!s.startsWith(respId)) continue
        s = s.substring(2)
        if (can && s.length >= 2) s = s.substring(2)
        var i = 0
        while (i + 4 <= s.length) {
            val b1 = s.substring(i, i + 2).toInt(16)
            val b2 = s.substring(i + 2, i + 4).toInt(16)
            if (b1 != 0 || b2 != 0) out += decodeDtc(b1, b2)
            i += 4
        }
    }
    return out.toList()
}
